"""PreToolUse hook. Refuses an edit to a file that another run has claimed.

Exit 2 refuses the tool call and stderr is fed back to Claude. Any failure here
also exits 2, because Claude Code lets the edit through on any other exit code.

Nothing in this repo registers this hook, and that is deliberate: a nested
.claude/settings.json would make anybody who clones this run it against their
own agent. Wire it up yourself, in your own project's settings, when you want it.

Needs an absolute ITERUM_DB, so every worktree reads the same database, and a
FLEET_RUN_ID for each agent. Reads the hook payload on stdin:

    echo '{"tool_name":"Edit","tool_input":{"file_path":"/repo/parser.py"}}' \\
      | ITERUM_DB=/repo/agent.db FLEET_RUN_ID=agent-b-run uv run python fleet/edit_hook.py
"""

import json
import os
import sys
import time
from pathlib import Path

# Run as a script, sys.path[0] is fleet/. The repo root is what makes `fleet` importable.
sys.path[0] = str(Path(__file__).resolve().parent.parent)

PATH_FIELDS = {"Edit": "file_path", "Write": "file_path", "NotebookEdit": "notebook_path"}


def refusal(payload):
    """The message refusing this tool call, or None to allow it."""
    from fleet import claim, db  # imported here so a failure is refused, not crashed on

    tool = payload["tool_name"]
    if tool not in PATH_FIELDS:
        return None
    resource = claim.file_resource(payload["tool_input"][PATH_FIELDS[tool]])
    if resource is None:
        return None

    run_id = os.environ.get("FLEET_RUN_ID")
    if not run_id:
        return "FLEET_RUN_ID is not set, so this hook cannot tell who is editing. Set it for this agent."
    if not (db.DB.is_absolute() and db.DB.exists()):
        return f"ITERUM_DB must be the absolute path of an existing database, not {str(db.DB)!r}."

    con = db.connect()
    try:
        row = con.execute("SELECT * FROM claims WHERE resource=?", (resource,)).fetchone()
    finally:
        con.close()

    if row and row["expires_at"] > time.time() and row["run_id"] != run_id:
        until = time.strftime("%H:%M:%S", time.localtime(row["expires_at"]))
        return (
            f"{resource} is claimed by {row['agent']} until {until}. "
            "Wait until then or work on something else. Do not edit this file."
        )
    return None


def main():
    try:
        message = refusal(json.load(sys.stdin))
    except Exception as e:
        message = f"The edit hook failed, so this edit is refused: {e!r}"
    if message:
        print(message, file=sys.stderr)
        sys.exit(2)


if __name__ == "__main__":
    main()
